#!/usr/bin/env python3
"""Generate generated/source/openarm_bi_leap.urdf: the OpenArm dual-arm body with a
LEAP Hand (vendor/leap_hand) on both link7 flanges.

Same layout as openarm_bi_rh56f1.urdf: openarm_bimanual_no_mount.urdf minus its empty
gripper_mount frames, plus each hand renamed with a ``leap_{side}_`` prefix (the vendor
joint names are bare "0".."15") with its palm fixed to link7 by ``mount_{side}_link7_to_leap``.

The mount transform is read from the ROS assembly (assemblies/openarm_modular_dual_leap.xacro,
args ``{side}_mount_xyz/rpy``), so the adapter is edited in one place for both the ROS
description and the RL asset. The hand is oriented like RH56F1: fingers along link7 +z,
palm facing link7 -y (right) / +y (left), index finger toward link7 +x.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from pathlib import Path

from gen_leap_hand_xacro import VENDOR, XACRO_NS, hand_elements
from generate_rl_urdf import _compose_origins

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "generated" / "source" / "openarm_bimanual_no_mount.urdf"
ASSEMBLY = ROOT / "assemblies" / "openarm_modular_dual_leap.xacro"
OUT = ROOT / "generated" / "source" / "openarm_bi_leap.urdf"


def mount_origin(side: str) -> tuple[str, str]:
    """(xyz, rpy) of link7 -> hand seat frame, from the assembly's arg defaults."""
    args = {a.get("name"): a.get("default") for a in ET.parse(ASSEMBLY).getroot().iter(f"{{{XACRO_NS}}}arg")}
    return args[f"{side}_mount_xyz"], args[f"{side}_mount_rpy"]


def build() -> ET.ElementTree:
    tree = ET.parse(BASE)
    robot = tree.getroot()
    robot.set("name", "openarm_bi_leap")
    for el in list(robot):
        name = el.get("name") or ""
        if "gripper_mount" in name:
            robot.remove(el)
    robot.insert(0, ET.Comment(
        " OpenArm bimanual base from openarm_bimanual_no_mount.urdf with LEAP Hand left/right"
        " attached directly to link7. Generated by tools/gen_leap_bi_source.py - do not edit. "))
    for side in ("left", "right"):
        # The geometry-less seat frame would become a 1e-5 kg PhysX body
        # (docs/ROBOT_ASSET_SPEC.md §3), so it is folded into the mount joint:
        # link7 -> palm_lower directly, like the official LEAP URDF (palm_lower is its root).
        p = f"leap_{side}_"
        hand = [el for el in hand_elements(side, p, lambda f: f"file://{(VENDOR / f).resolve()}")
                if el.get("name") != p + "mount"]
        joint = next(el for el in hand if el.get("name") == p + "mount_joint")
        xyz, rpy = mount_origin(side)
        mount = ET.Element("joint")
        ET.SubElement(mount, "origin", xyz=xyz, rpy=rpy)
        _compose_origins(mount, joint)
        joint.set("name", f"mount_{side}_link7_to_leap")
        joint.find("parent").set("link", f"openarm_{side}_link7")
        robot.extend(hand)
    ET.indent(tree, space="  ")
    return tree


def main() -> None:
    build().write(OUT, encoding="utf-8", xml_declaration=True)
    print(f"generated {OUT}")


if __name__ == "__main__":
    main()
