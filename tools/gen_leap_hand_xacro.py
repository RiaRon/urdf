#!/usr/bin/env python3
"""Generate leap_hand_description/urdf/leap_hand_macro.xacro from the vendor URDFs.

The vendor LEAP URDFs (vendor/leap_hand, dex-urdf copy) use bare joint names
("0".."15") that collide between the two hands, so each hand becomes a xacro macro
(``leap_hand_left`` / ``leap_hand_right``) that prefixes every name with ``${prefix}``.

dex-urdf's ``base`` frame is replaced by ``${prefix}mount``: a seat frame at the
bottom-center of the palm, x = palm normal, y = toward the index finger, z = toward
the fingertips. An assembly attaches the hand by placing this frame on the flange.

``hand_elements()`` is shared with tools/gen_leap_bi_source.py so the ROS assembly
and the RL source URDF carry the same hand.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Callable

from generate_rl_urdf import _compose_origins

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "vendor" / "leap_hand"
OUT = ROOT / "leap_hand_description" / "urdf" / "leap_hand_macro.xacro"
XACRO_NS = "http://www.ros.org/wiki/xacro"

# Bottom-center of the palm_lower visual mesh AABB, in the vendor `base` frame
# (x = palm normal, y = toward index, z = toward fingers). The two dex-urdf hands
# put `base` in slightly different places, so the value is per side.
PALM_BOTTOM_CENTER = {
    "left": (0.000278, 0.000630, -0.005500),
    "right": (0.011700, 0.001514, -0.002000),
}


def hand_elements(side: str, prefix: str, mesh_uri: Callable[[str], str]) -> list[ET.Element]:
    """Vendor hand links/joints, renamed with ``prefix``, rooted at ``{prefix}mount``."""
    hand = ET.parse(VENDOR / f"leap_hand_{side}.urdf").getroot()
    for el in hand.iter():
        if el.tag in ("link", "joint"):
            el.set("name", prefix + el.get("name"))
        elif el.tag in ("parent", "child"):
            el.set("link", prefix + el.get("link"))
        elif el.tag == "mimic":
            el.set("joint", prefix + el.get("joint"))
        elif el.tag == "mesh":
            el.set("filename", mesh_uri(el.get("filename")))
    elements = [el for el in hand if el.tag in ("link", "joint") and el.get("name") != prefix + "base"]

    # base_joint (base -> palm) becomes mount_joint (seat -> palm): seat = base shifted to the palm bottom-center.
    joint = next(el for el in elements if el.get("name") == prefix + "base_joint")
    seat = ET.Element("joint")
    ET.SubElement(seat, "origin", xyz=" ".join(f"{-v:.9g}" for v in PALM_BOTTOM_CENTER[side]), rpy="0 0 0")
    _compose_origins(seat, joint)
    joint.set("name", prefix + "mount_joint")
    joint.find("parent").set("link", prefix + "mount")
    return [ET.Element("link", name=prefix + "mount")] + elements


def build() -> ET.ElementTree:
    ET.register_namespace("xacro", XACRO_NS)
    robot = ET.Element("robot", name="leap_hand_macro")
    robot.append(ET.Comment(
        " GENERATED by tools/gen_leap_hand_xacro.py from vendor/leap_hand - do not edit. "))
    for side in ("left", "right"):
        macro = ET.SubElement(robot, f"{{{XACRO_NS}}}macro", name=f"leap_hand_{side}", params="prefix:=''")
        macro.extend(hand_elements(side, "${prefix}",
                                   lambda f: f"package://leap_hand_description/{f}"))
    tree = ET.ElementTree(robot)
    ET.indent(tree, space="  ")
    return tree


def main() -> None:
    build().write(OUT, encoding="utf-8", xml_declaration=True)
    print(f"generated {OUT}")


if __name__ == "__main__":
    main()
